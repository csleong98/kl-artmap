// Generates src/styles/typography.generated.css from tokens/typography.json (a Figma text-styles export).
// Re-run with `npm run build:typography` whenever the Figma export changes.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const dirname = path.dirname(fileURLToPath(import.meta.url));
const inFile = path.join(dirname, '..', 'tokens', 'typography.json');
const outFile = path.join(dirname, '..', 'src', 'styles', 'typography.generated.css');

// Figma font weight name -> CSS numeric font-weight.
// "Italic" isn't a real weight - Figma reports it this way when the family's style
// axis is selected instead of a weight; treat it as regular weight + italic style.
const WEIGHT_MAP = {
  Regular: 400,
  Medium: 500,
  SemiBold: 600,
  Bold: 700,
  ExtraBold: 800,
  Italic: 400,
};

// Font-family names must match the @font-face declarations shipped by the
// @fontsource packages loaded in .storybook/preview.tsx (e.g. @fontsource/geist-sans
// declares the family as "Geist Sans", not "Geist").
const FONT_STACKS = {
  Geist: `'Geist Sans', ui-sans-serif, system-ui, sans-serif`,
  Inter: `'Inter', ui-sans-serif, system-ui, sans-serif`,
};

// Known typo in the Figma file ("suble - semibold") -> normalized class name.
const NAME_OVERRIDES = {
  'suble - semibold': 'subtle-semibold',
};

function toClassName(name) {
  const normalized = NAME_OVERRIDES[name] ?? name;
  return normalized.trim().toLowerCase().replace(/\s+/g, '-');
}

function toRem(px) {
  const rem = px / 16;
  return `${Number(rem.toFixed(4))}rem`;
}

function toLetterSpacing(letterSpacing) {
  if (!letterSpacing || letterSpacing.value === 0) return null;
  if (letterSpacing.unit !== 'PERCENT') {
    throw new Error(`Unsupported letterSpacing unit: ${letterSpacing.unit}`);
  }
  const em = letterSpacing.value / 100;
  return `${Number(em.toFixed(4))}em`;
}

const { textStyles } = JSON.parse(readFileSync(inFile, 'utf8'));

const fontFamilyVars = Object.entries(FONT_STACKS)
  .map(([name, stack]) => `  --font-${name.toLowerCase()}: ${stack};`)
  .join('\n');

const classes = textStyles.map((style) => {
  const className = toClassName(style.name);
  const weight = WEIGHT_MAP[style.fontWeight];
  if (weight === undefined) {
    throw new Error(`Unmapped font weight "${style.fontWeight}" for style "${style.name}" - add it to WEIGHT_MAP.`);
  }
  const fontVar = `var(--font-${style.fontFamily.toLowerCase()})`;
  const letterSpacing = toLetterSpacing(style.letterSpacing);
  const isItalic = style.fontWeight === 'Italic';

  const declarations = [
    `font-family: ${fontVar};`,
    `font-weight: ${weight};`,
    `font-size: ${toRem(style.fontSize)};`,
  ];
  if (letterSpacing) declarations.push(`letter-spacing: ${letterSpacing};`);
  if (isItalic) declarations.push(`font-style: italic;`);

  return `.text-${className} {\n  ${declarations.join('\n  ')}\n}`;
});

const css = `/* AUTO-GENERATED by scripts/build-typography.mjs from tokens/typography.json - do not edit by hand. */

:root {
${fontFamilyVars}
}

${classes.join('\n\n')}
`;

mkdirSync(path.dirname(outFile), { recursive: true });
writeFileSync(outFile, css);
console.log(`[build-typography] Wrote ${path.relative(process.cwd(), outFile)}`);
